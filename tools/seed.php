    (api_id, title, slug, category_id, cuisine_id, description, instructions, image, prep_minutes, servings, difficulty, calories, is_published, author_id, created_at)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 1, 1, ?)');
$insIng = $pdo->prepare('INSERT INTO ingredients (title, kind) VALUES (?, ?)');
$findIng = $pdo->prepare('SELECT id FROM ingredients WHERE title = ?');
$insRI = $pdo->prepare('INSERT INTO recipe_ingredients (recipe_id, ingredient_id, amount) VALUES (?, ?, ?)');

$recipeIds = [];
$day = 1;
foreach ($recipes as $r) {
    $instructions = '';
    foreach ($r['steps'] as $i => $step) {
        $instructions .= ($i + 1) . '. ' . $step . "\n";
    }
    $created = sprintf('2026-10-%02d %02d:00:00', min(28, $day), 9 + ($day % 9));
    $insRecipe->execute([
        $r['api'], $r['title'], slugify($r['title']),
        $catId[$r['cat']], $cuiId[$r['cuisine']],
        $r['desc'], trim($instructions), $img($r['img']),
        $r['min'], $r['serv'], $r['diff'], $r['kcal'],
        $created,
    ]);
    $rid = (int)$pdo->lastInsertId();
    $recipeIds[] = $rid;

    foreach ($r['ing'] as [$name, $amount]) {
        $findIng->execute([$name]);
        $iid = $findIng->fetchColumn();
        if (!$iid) {
            $insIng->execute([$name, null]);
            $iid = (int)$pdo->lastInsertId();
        }
        $insRI->execute([$rid, $iid, $amount]);
    }
    $day++;
}

